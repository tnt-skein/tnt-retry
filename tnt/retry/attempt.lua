--- Одна попытка и разбор того, чем она кончилась.
---
--- Договор один на весь пакет и живёт в одном месте нарочно: и цикл
--- повторов, и размыкатель судят об удаче одинаково, а два независимых
--- суждения об одном и том же однажды расходятся — и тогда размыкатель
--- считает отказом то, что повторы считают успехом.
---
--- Отказом считается `nil` или `false` первым значением — так отвечает
--- всякая функция, у которой отказ — пара `nil, err`. Исключение тоже
--- считается отказом: клиент, роняющий узел чужой ошибкой, не годится
--- ни на что, а сетевые библиотеки бросают охотно.
---
--- Чем поступились: наружу проходит ровно пара «значение и причина».
--- Действие, отвечающее тремя значениями, третьего не досчитается —
--- зато поведение предсказуемо и одинаково у всех, кто зовёт отсюда.

local Module = {}

--- Что сказать, когда действие отказало молча.
---
--- `return nil` без причины — обычное дело в чужом коде, и пустой отказ
--- доходит до вызывающего как «не вышло, а почему — не скажу». Подстановка
--- делается здесь, а не в цикле повторов: тогда и размыкатель, и журнал,
--- и вызывающий видят одну и ту же причину.
Module.NO_REASON = 'действие отказало и причины не назвало'

--- Причина отказа, назвал её кто-нибудь или нет.
---@param err any
---@return any
function Module.reason(err)
    if err == nil then
        return Module.NO_REASON
    end

    return err
end

--- Выполняет действие и разбирает исход.
---@param action fun(context: table): any, any
---@param context table Что известно о попытке: номер, срок, потраченное
---@return boolean ok Вышло ли
---@return any value Что вернуло действие
---@return any err Причина отказа либо второе значение удачного действия
function Module.once(action, context)
    -- Брошенное приходит первым возвращением pcall и является причиной,
    -- а не значением: `error('сеть пропала')` — это отказ, а не результат.
    local called, value, err = pcall(action, context)

    if not called then
        return false, nil, Module.reason(value)
    end

    if value == nil or value == false then
        return false, nil, Module.reason(err)
    end

    return true, value, err
end

return Module
